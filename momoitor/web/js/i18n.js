let _currentLang = "en";

function t(key) {
    return (LANGS[_currentLang] && LANGS[_currentLang][key]) || LANGS.en[key] || key;
}

function getCurrentLang() {
    return _currentLang;
}

// i18n 内嵌链接：译文里可用 Markdown 式 [文字](URL) 嵌入链接，渲染为可点击的 <a>。
// 仅当匹配到该语法时才走 innerHTML；其余译文沿用 textContent。
const I18N_LINK_RE = /\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g;

function i18nToHtml(text) {
    I18N_LINK_RE.lastIndex = 0;                 // 全局正则需先复位
    if (!I18N_LINK_RE.test(text)) return null;  // 无链接 -> 沿用 textContent
    I18N_LINK_RE.lastIndex = 0;
    return escapeHtml(text).replace(I18N_LINK_RE,
        '<a class="i18n-link" href="$2" target="_blank" rel="noopener">$1</a>');
}

function applyLang(lang) {
    if (lang) _currentLang = lang;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        const text = t(key);
        if (text) {
            const html = i18nToHtml(text);
            el.innerHTML = html !== null ? html : text;   // 有链接走 innerHTML，否则 textContent
        }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        const text = t(key);
        if (text) el.placeholder = text;
    });
    document.querySelectorAll("[data-i18n-label]").forEach(el => {
        const key = el.getAttribute("data-i18n-label");
        const text = t(key);
        if (text) el.label = text;
    });
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
        const key = el.getAttribute("data-i18n-title");
        const text = t(key);
        if (text) el.title = text;
    });
}

function escapeHtml(str) {
    var div = document.createElement('div');
    div.appendChild(document.createTextNode(str));
    return div.innerHTML;
}

function setText(id, val) {
    const el = document.getElementById(id);
    if (el && el.textContent !== val) el.textContent = val;
}

function pad2(n) {
    return n < 10 ? '0' + n : '' + n;
}
